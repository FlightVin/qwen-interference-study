"""Write harness recipes (exp/<expid>.sh) for study s02 training runs and branches. Orchestration helper only.

A run is defined by a JSON spec (one object, or a list):
  {"expid": "qis-s02-e1-R-s1", "part": "general", "time": "08:00:00",
   "bundle": "s02-v1", "bundle_spec": "add9:d4,...", "n_train": 4000, "n_eval": 64,
   "config": {...training config keys of qis.train.run, without paths...},
   "hypothesis": "one or two lines",
   "after": null}
Paths are filled in: bundle $S02/data/<bundle>.json, run dir $S02/runs/<expid>, checkpoints $S02/ckpt/<expid>.
"init_ckpt" in config may name another run as "run:<expid>:<round>" (resolved to its round_NNNN directory).
Usage: python -m qis.s02.make_exps --spec FILE.json --expdir DIR [--test-exit ROUND]
"""
import argparse
import json
import os

TEMPLATE = r'''#!/usr/bin/env bash
#EXP gpus=1 cpus=8 mem=96G time={time} part={part}{exclude}
# HYPOTHESIS: {hypothesis}
# Generated by qis.s02.make_exps (study Nov-15-2026-02). Bundle {bundle} = {bundle_spec} (n_train {n_train}, n_eval {n_eval}).
export PROJ_DATA="/data/user_data/$USER/qis"
export S02="$PROJ_DATA/s02"
export VENV="$PROJ_DATA/env/venv-s02"
export HF_HOME="$PROJ_DATA/hf"
export HF_HUB_OFFLINE=1
export PYTHONPATH="$PWD/src"
export VLLM_ENABLE_V1_MULTIPROCESSING=0
export VLLM_USE_FLASHINFER_SAMPLER=0
export PATH="$VENV/bin:$PATH"
export MODEL="$PROJ_DATA/hf/hub/models--Qwen--Qwen3-1.7B/snapshots/70d244cc86ccca08cf5af4e1e306ecf908b1ad5e"
export BUNDLE="$S02/data/{bundle}.json"
export BSPEC="{bundle_spec}"
export RUN="{expid}"
export W="$S02/runs/$RUN"
export CK="$S02/ckpt/$RUN"
{extra_env}
phase precheck "false" '
    test -f "$VENV/.complete" || {{ echo "PRECONDITION FAILED: venv-s02 missing"; exit 1; }}
    used=$(nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits | head -1)
    [ "$used" -lt 2048 ] || {{ echo "GPU already holds ${{used}} MiB on $(hostname)"; exit 1; }}
    nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv > "$AE_RESULTS/gpu.txt"
    mkdir -p "$W" "$CK" "$S02/data"
'
phase bundle "test -s $BUNDLE" '
    t="$BUNDLE.tmp.$SLURM_JOB_ID"
    python -m qis.s02.tasks --out "$t" --spec "$BSPEC" --n-train {n_train} --n-eval {n_eval} > "$t.log"
    mv "$t" "$BUNDLE"; mv "$t.log" "$BUNDLE.log"
'
phase config "test -s $W/config.json" '
    sha=$(sha256sum "$BUNDLE" | cut -d" " -f1)
    python - <<PY
import json, os
cfg = json.loads(os.environ["CFG_JSON"])
cfg.update(run_id=os.environ["RUN"], attempt_id="a1", bundle=os.environ["BUNDLE"], bundle_sha256="$sha",
           model=os.environ["MODEL"], out_dir=os.environ["W"], ckpt_dir=os.environ["CK"],
           ckpt_lock_root=os.environ["S02"] + "/ckpt")
ic = cfg.get("init_ckpt")
if isinstance(ic, str) and ic.startswith("run:"):
    _, run, rnd = ic.split(":")
    cfg["init_ckpt"] = os.path.join(os.environ["S02"], "ckpt", run, "round_%04d" % int(rnd))
    assert os.path.isdir(cfg["init_ckpt"]), "init checkpoint missing: " + cfg["init_ckpt"]
json.dump(cfg, open(os.environ["W"] + "/config.json", "w"), indent=1)
PY
    cp "$W/config.json" "$AE_RESULTS/config.json"
'
phase train "test -f $W/RUN_COMPLETE" '
    rc=0; python -m qis.train.run --config "$W/config.json" >> "$W/stdout.log" 2>&1 || rc=$?
    grep -v "^INFO\|it/s\]" "$W/stdout.log" | tail -15
    cp "$W/metrics.jsonl" "$AE_RESULTS/metrics.jsonl" 2>/dev/null || true
    if [ $rc -eq 143 ]; then scontrol requeue $SLURM_JOB_ID; sleep 900; fi
    exit $rc
'
phase export "false" '
    cp "$W/metrics.jsonl" "$W/config.json" "$AE_RESULTS/"
    du -sh "$CK" > "$AE_RESULTS/ckpt_du.txt" 2>&1 || true
'
'''


def write(spec, expdir, test_exit=None):
    cfg = dict(spec["config"])
    extra = [f"export CFG_JSON='{json.dumps(cfg)}'"]
    if test_exit:
        extra.append(f"export QIS_EXIT_AFTER_ROUND={int(test_exit)}")
    ex = f" exclude={spec['exclude']}" if spec.get("exclude") else ""
    text = TEMPLATE.format(time=spec.get("time", "08:00:00"), part=spec.get("part", "general"), exclude=ex,
                           hypothesis=spec["hypothesis"], bundle=spec["bundle"], bundle_spec=spec["bundle_spec"],
                           n_train=spec.get("n_train", 4000), n_eval=spec.get("n_eval", 64), expid=spec["expid"],
                           extra_env="\n".join(extra))
    assert "'" not in json.dumps(cfg), "config must not contain single quotes"
    path = os.path.join(expdir, spec["expid"] + ".sh")
    with open(path, "w") as f:
        f.write(text)
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--expdir", required=True)
    ap.add_argument("--test-exit", type=int, default=None)
    a = ap.parse_args()
    specs = json.load(open(a.spec))
    for s in (specs if isinstance(specs, list) else [specs]):
        print(write(s, a.expdir, a.test_exit))


if __name__ == "__main__":
    main()
